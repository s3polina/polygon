class Solution {
public:
    int candy(vector<int>& ratings) {
        int n = ratings.size(); // Получаем количество детей
        int totalCandies = n;   // Изначально каждому ребенку дается по 1 конфете
        int i = 1;              // Начинаем с первого ребенка

        while (i < n) {
            // Если текущий ребенок имеет такую же оценку, как и предыдущий, просто переходим к следующему
            if (ratings[i] == ratings[i - 1]) {
                i++;
                continue;
            }

            int currentPeak = 0; // Переменная для отслеживания пиков (возрастающих последовательностей)
            // Пока текущая оценка выше предыдущей
            while (i < n && ratings[i] > ratings[i - 1]) {
                currentPeak++;                     // Увеличиваем счетчик пика
                totalCandies += currentPeak;      // Добавляем к общему количеству конфет
                i++;                               // Переходим к следующему ребенку
            }

            // Если достигнут конец массива, возвращаем общее количество конфет
            if (i == n) {
                return totalCandies;
            }

            int currentValley = 0; // Переменная для отслеживания впадин (убывающих последовательностей)
            // Пока текущая оценка ниже предыдущей
            while (i < n && ratings[i] < ratings[i - 1]) {
                currentValley++;                    // Увеличиваем счетчик впадины
                totalCandies += currentValley;      // Добавляем к общему количеству конфет
                i++;                                 // Переходим к следующему ребенку
            }

            // Уменьшаем общее количество конфет на минимальное значение между пиком и впадиной
            totalCandies -= min(currentPeak, currentValley);
        }

        return totalCandies; // Возвращаем общее количество конфет
    }
};
